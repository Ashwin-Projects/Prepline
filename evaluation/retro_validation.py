"""
Retrospective validation — not the participant pilot.

Leave-one-report-out on the collected interview reports (Amazon, Microsoft, Flipkart; Google is below the density
gate): for each report, recompute I(t) from the other reports (config v1.2 scoring, unchanged), take the top-10
topics by importance, and measure the share of the held-out report's mapped topics that are in that top-10. The
company's hit rate is the mean over held-out reports with at least one mapped topic. Baseline: the same number of
topics drawn at random from the 46 interview skills, 1000 seeded draws per company.

Writes results/validation/RETRO_VALIDATION.md, retro_validation.json and retro_validation_hit_rate.png (never
overwritten without --replace).

Usage:
    python evaluation/retro_validation.py [--replace]
"""
import argparse
import json
import os
import random
import sys
import tempfile
import time
from datetime import datetime, timezone
from statistics import mean
from typing import Any, Callable, Dict, List, Set

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

LABEL = "Retrospective validation — not the participant pilot"
OUT_DIR = os.path.join(ROOT, "results", "validation")
FILES = ("RETRO_VALIDATION.md", "retro_validation.json", "retro_validation_hit_rate.png")
TOP_K = 10
SEED = 20261023
DRAWS = 1000

ImportanceFn = Callable[[List[Dict[str, str]], int], Dict[str, float]]
HeldFn = Callable[[List[Dict[str, str]]], Set[str]]


def _top(importance: Dict[str, float], k: int) -> List[str]:
    ranked = sorted((t for t, v in importance.items() if v > 0), key=lambda t: (-importance[t], t))
    return ranked[:k]


def loo_folds(rows: List[Dict[str, str]], importance_fn: ImportanceFn, held_fn: HeldFn, k: int = TOP_K) -> List[Dict[str, Any]]:
    """rows: the included (filtered) question rows of one target. One fold per report, in report-id order."""
    reports = sorted({r["report_id"] for r in rows})
    folds = []
    for report in reports:
        train = [r for r in rows if r["report_id"] != report]
        top = _top(importance_fn(train, len(reports) - 1), k)
        held = held_fn([r for r in rows if r["report_id"] == report])
        hits = sorted(held & set(top))
        folds.append({"report_id": report, "top": top, "held_topics": sorted(held), "hits": hits,
                      "hit_rate": len(hits) / len(held) if held else None})
    return folds


def summarize(folds: List[Dict[str, Any]]) -> Dict[str, Any]:
    scored = [f["hit_rate"] for f in folds if f["hit_rate"] is not None]
    return {"n_reports": len(folds), "n_folds_scored": len(scored), "n_folds_skipped": len(folds) - len(scored),
            "hit_rate": mean(scored) if scored else None}


def random_baseline(folds: List[Dict[str, Any]], pool: List[str], draws: int = DRAWS, seed: int = SEED) -> Dict[str, Any]:
    """Each fold draws len(top) topics uniformly from pool; a draw's value is the mean hit rate over scored folds."""
    rng = random.Random(seed)
    scored = [f for f in folds if f["hit_rate"] is not None]
    values = []
    for _ in range(draws):
        rates = [len(set(f["held_topics"]) & set(rng.sample(pool, len(f["top"])))) / len(f["held_topics"]) for f in scored]
        values.append(mean(rates) if rates else 0.0)
    values.sort()
    return {"mean": mean(values), "p2_5": values[int(0.025 * (draws - 1))], "p97_5": values[int(0.975 * (draws - 1))],
            "draws": draws, "seed": seed}


def assemble(companies: List[Dict[str, Any]], seed: int = SEED, draws: int = DRAWS, k: int = TOP_K) -> Dict[str, Any]:
    return {"label": LABEL, "generated_at": datetime.now(timezone.utc).isoformat(), "top_k": k, "seed": seed,
            "draws": draws, "scoring_config": "config/scoring_v1.2.json", "companies": companies}


def _pct(x):
    return "n/a" if x is None else f"{x * 100:.1f} %"


def build_markdown(result: Dict[str, Any]) -> str:
    lines = [
        f"# {LABEL}",
        "",
        f"Generated by `evaluation/retro_validation.py` on {result['generated_at'][:10]}. Leave-one-report-out on the "
        "collected interview reports: for each report, I(t) is recomputed from the other reports with the frozen "
        f"scoring config v1.2, and its top-{result['top_k']} topics are compared with the topics the held-out report's "
        "questions map to. Baseline: the same number of topics drawn at random from the 46 interview skills "
        f"({result['draws']} draws, seed {result['seed']}). This is **not** the participant pilot (Phase 16): it reuses "
        "the same public reports PREPLINE is built from.",
        "",
        "| Company | Reports (scored folds) | PREPLINE top-10 hit rate | Random baseline (95 % of draws) |",
        "|---|---|---|---|",
    ]
    for c in result["companies"]:
        b = c["baseline"]
        lines.append(f"| {c['label']} | {c['n_reports']} ({c['n_folds_scored']}) | {_pct(c['hit_rate'])} | "
                     f"{_pct(b['mean'])} ({_pct(b['p2_5'])}–{_pct(b['p97_5'])}) |")
    lines += [
        "",
        "Reading it: the hit rate says how often a new report's topics were already among the most important topics of "
        "the other reports. Folds where the held-out report maps to no topic are skipped (counted in the table).",
        "",
        "Limitations: small samples (15–18 reports per company); one source site, so reports share writing style; the "
        "held-out topics come from the same matcher as the top-10 (mapping errors cancel rather than show); the "
        "random interval describes the draws, not a significance test.",
        "",
        f"![Hit rate vs random baseline]({FILES[2]})",
        "",
    ]
    return "\n".join(lines)


def write_chart(result: Dict[str, Any], path: str) -> None:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    companies = result["companies"]
    labels = [c["label"] for c in companies]
    fig, ax = plt.subplots(figsize=(7, 3.6), dpi=200)
    fig.patch.set_facecolor("#fcfcfb")
    ax.set_facecolor("#fcfcfb")
    xs = range(len(companies))
    ax.bar(xs, [(c["hit_rate"] or 0) * 100 for c in companies], width=0.5, color="#2a78d6", label="PREPLINE top-10")
    for x, c in zip(xs, companies):
        b = c["baseline"]
        ax.plot([x - 0.3, x + 0.3], [b["mean"] * 100] * 2, color="#52514e", linewidth=2,
                label="Random top-10 (mean)" if x == 0 else None)
        ax.text(x, (c["hit_rate"] or 0) * 100 + 2, _pct(c["hit_rate"]), ha="center", fontsize=9, color="#0b0b0b")
    ax.set_xticks(list(xs), labels, fontsize=9, color="#52514e")
    ax.set_ylim(0, 105)
    ax.set_ylabel("Held-out report topics in top-10 (%)", fontsize=9, color="#52514e")
    ax.tick_params(colors="#52514e", labelsize=9)
    for side in ("top", "right", "left"):
        ax.spines[side].set_visible(False)
    ax.grid(axis="y", color="#e6e5e0", linewidth=0.8)
    ax.set_axisbelow(True)
    ax.legend(frameon=False, fontsize=8, loc="upper right")
    ax.set_title(f"{LABEL}: leave-one-report-out hit rate", loc="left", fontsize=10, color="#0b0b0b")
    fig.tight_layout()
    fig.savefig(path, facecolor=fig.get_facecolor())
    plt.close(fig)


def write_outputs(result: Dict[str, Any], out_dir: str = OUT_DIR, replace: bool = False) -> None:
    paths = [os.path.join(out_dir, name) for name in FILES]
    if not replace and any(os.path.exists(p) for p in paths):
        raise FileExistsError(f"retrospective validation results exist in {out_dir}; pass --replace to regenerate")
    os.makedirs(out_dir, exist_ok=True)
    with open(paths[0], "w", encoding="utf-8") as f:
        f.write(build_markdown(result))
    with open(paths[1], "w", encoding="utf-8") as f:
        json.dump(result, f, indent=2)
    write_chart(result, paths[2])


def scoring_functions():
    """Real I(t) and held-out topics, both through pipeline.scoring.calculate_topic_importance (config v1.2)."""
    import pipeline.unmapped_terms_logger as unmapped_terms_logger
    from pipeline.scoring import calculate_topic_importance

    unmapped_terms_logger.LOG_PATH = os.path.join(tempfile.mkdtemp(prefix="prepline_retro_"), "unmapped_terms.log")

    def importance(rows, n_reports):
        res = calculate_topic_importance(rows, total_reports_count=n_reports)
        return {i["topic_id"]: i["importance"] for i in res["interview_importance"]}

    def held(rows):
        res = calculate_topic_importance(rows, total_reports_count=1)
        return {i["topic_id"] for i in res["interview_importance"] if i["importance"] > 0}

    return importance, held


def run(replace: bool = False) -> Dict[str, Any]:
    from evaluation.pilot.form_spec import profiles
    from pipeline.config import load_targets
    from pipeline.interview_parser import filter_questions, load_questions_csv
    from pipeline.scoring import DEFAULT_TAXONOMY_PATH, load_taxonomy_nodes

    pool = sorted(n["topic_id"] for n in load_taxonomy_nodes(DEFAULT_TAXONOMY_PATH) if n["type"] == "granular_skill")
    scored = {p["target_id"] for p in profiles() if p["status"] == "SUCCESS"}
    importance, held = scoring_functions()
    companies = []
    for t in load_targets():
        if t["id"] not in scored:
            print(f"[{t['id']}] skipped: no PREPLINE profile (below the density gate)", flush=True)
            continue
        t0 = time.time()
        rows, _ = filter_questions(load_questions_csv(t["questions_csv"]))
        folds = loo_folds(rows, importance, held)
        company = {"target_id": t["id"], "label": f"{t['company']} {t['role']}", **summarize(folds),
                   "baseline": random_baseline(folds, pool), "folds": folds}
        companies.append(company)
        print(f"[{t['id']}] {company['n_reports']} reports, hit rate {_pct(company['hit_rate'])} vs random "
              f"{_pct(company['baseline']['mean'])} in {time.time() - t0:.0f}s", flush=True)
    result = assemble(companies)
    write_outputs(result, OUT_DIR, replace)
    return result


def main() -> None:
    parser = argparse.ArgumentParser(description=LABEL)
    parser.add_argument("--replace", action="store_true", help="regenerate existing results")
    run(parser.parse_args().replace)
    print(f"Wrote {OUT_DIR}")


if __name__ == "__main__":
    main()
