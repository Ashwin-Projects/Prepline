"""
Writes docs/pilot/FORM.md (ready-to-copy Google Form questions) and data/pilot/pilot_template.csv (the header of the
form's CSV export) from evaluation/pilot/form_spec.py.

Usage:
    python evaluation/pilot/build_form.py
"""
import csv
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, ROOT)

from evaluation.pilot import form_spec as fs


def form_markdown() -> str:
    p = fs.profiles()
    scored = [x for x in p if x["gaps"]]
    lines = [
        "# PREPLINE pilot — Google Form questions",
        "",
        "Generated by `evaluation/pilot/build_form.py` from the saved v1.2 results; copy each question into Google Forms",
        "exactly as written (titles must match `data/pilot/pilot_template.csv` for the analysis to read the export).",
        "",
        "**Form settings:** Do not collect email addresses (Settings → Responses → Collect email addresses: *Do not",
        "collect*). Do not require sign-in. Limit to 1 response is off (it needs sign-in). Do not add a name field.",
        "",
        "Before the questions, paste the information sheet from `docs/pilot/PILOT_PROTOCOL.md` (Consent section).",
        "",
        "## Section 1 — Consent and background",
        "",
        f"1. **{fs.CONSENT}** — Checkboxes, required, one option: “{fs.CONSENT_YES}”.",
        f"2. **{fs.PARTICIPANT}** — Short answer, required. Validation: regular expression `P[0-9]{{2}}`.",
        f"3. **{fs.COMPANY}** — Multiple choice, required: " + "; ".join(f"“{x['label']}”" for x in p) + ".",
        f"4. **{fs.ROLE}** — Short answer, required.",
        f"5. **{fs.ROUNDS}** — Checkboxes: " + "; ".join(f"“{r}”" for r in fs.ROUND_OPTIONS) + ".",
        f"6. **{fs.TOPICS}** — Checkboxes (tick every topic you were asked about in any round), options in this order, "
        f"plus “{fs.NONE_OF_THESE}”:",
        "",
    ]
    lines += [f"   - {t}" for t in fs.topic_options()]
    lines += [f"   - {fs.NONE_OF_THESE}", "",
              "## Section 2 — Gap relevance (go to the section for the company in question 3)",
              "",
              "Use “Go to section based on answer” on question 3. Each section shows the top priority gaps PREPLINE",
              "reports for that company, as a multiple-choice grid with columns " + ", ".join(fs.RATING_SCALE) + ".",
              "Grid instruction text: “How well does each gap match your real weak areas for this interview? 1 = not at all,",
              "5 = exactly; N/A = I can't judge.”", ""]
    for x in scored:
        lines += [f"### {fs.GAP_PREFIX} {x['label']}", "", "Grid title: **" + f"{fs.GAP_PREFIX} {x['label']}" + "**. Grid rows (copy exactly):", ""]
        lines += [f"- `{i}. {g}`" for i, g in enumerate(x["gaps"], 1)]
        lines.append("")
    for x in p:
        if not x["gaps"]:
            lines += [f"*{x['label']}: no section — PREPLINE has no score for it ({x['status']}); respondents skip to "
                      f"Section 3.*", ""]
    lines += ["## Section 3 — Usefulness", "",
              f"Multiple-choice grid titled **{fs.USEFULNESS}**, columns 1–5 (1 = strongly disagree, 5 = strongly agree), rows:",
              ""]
    lines += [f"{i}. {item}" for i, item in enumerate(fs.USEFULNESS_ITEMS, 1)]
    lines += ["", f"Then **{fs.COMMENTS}** — Paragraph, optional.", ""]
    return "\n".join(lines)


def main() -> None:
    os.makedirs(os.path.dirname(fs.FORM_PATH), exist_ok=True)
    os.makedirs(os.path.dirname(fs.TEMPLATE_PATH), exist_ok=True)
    with open(fs.FORM_PATH, "w", encoding="utf-8") as f:
        f.write(form_markdown())
    with open(fs.TEMPLATE_PATH, "w", encoding="utf-8", newline="") as f:
        csv.writer(f).writerow(fs.columns())
    print(f"Wrote {fs.FORM_PATH} and {fs.TEMPLATE_PATH}")


if __name__ == "__main__":
    main()
