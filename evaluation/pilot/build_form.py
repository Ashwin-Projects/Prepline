"""
Writes, from evaluation/pilot/form_spec.py:
  docs/pilot/FORM.md            the hand-built Google Form, question by question, with exact titles, rows and options
  data/pilot/pilot_template.csv the header of the form's CSV export

Usage:
    python evaluation/pilot/build_form.py
"""
import csv
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, ROOT)

from evaluation.pilot import form_spec as fs

def form_markdown() -> str:
    q = lambda s: f"“{s}”"
    p = fs.profiles()
    lines = [
        "# PREPLINE pilot — Google Form (built by hand)",
        "",
        "Generated by `evaluation/pilot/build_form.py`; do not edit by hand. Copy every title, row and option",
        "**exactly** (the analysis matches the CSV export column titles, see `data/pilot/pilot_template.csv`).",
        "",
        "**Settings:** Do not collect email addresses. Do not require sign-in. No name or roll-number field.",
        f"Form title {q(fs.FORM_TITLE)}; description {q(fs.DESCRIPTION)}",
        "",
        "## Section 1 — Consent and company",
        "",
        f"- **Consent** — Checkboxes, required, one option: {q(fs.CONSENT_YES)} (the question title is free; the "
        "analysis finds consent by this answer).",
        f"- **Q1 {fs.COMPANY}** — Multiple choice, required, *Go to section based on answer*: "
        + "; ".join(f"{q(x['company'])} → section {q(x['company'])}" for x in p) + ".",
        "",
    ]
    for x in p:
        lines += [
            f"## Section {q(x['company'])} (one per company; identical except the Q2 rows)",
            "",
            f"- **Q2 {fs.Q2}** — Multiple-choice grid, require a response in each row: off.",
            "  Columns: " + ", ".join(q(c) for c in fs.GAP_SCALE) + ".",
            f"  Rows ({len(x['gaps'])}, {x['company']}'s top-{fs.TOP_N} priority gaps from the saved {fs.RESULTS_VERSION} "
            "results, in rank order):",
            "",
        ]
        lines += [f"  {i}. `{g}`" for i, g in enumerate(x["gaps"], 1)]
        lines += [
            "",
            f"- **Q3 {fs.Q3}** — Multiple choice, required, *Go to section based on answer*: "
            f"{q(fs.YES)} → section {q('Track A')}; {q(fs.NO)} → section {q('Rating')}.",
            "",
        ]
    lines += [
        "## Section “Track A” (Q3 = Yes)",
        "",
        f"- **Q4 {fs.Q4}** — Checkboxes, required. Options ({len(fs.TOPIC_OPTIONS)}), in this order:",
        "",
    ]
    lines += [f"  {i}. `{o}`" for i, o in enumerate(fs.TOPIC_OPTIONS, 1)]
    lines += [
        "",
        f"  Use a plain option named {q(fs.OTHER)} (Google's built-in “Other:” text box also works: its text counts as Other).",
        "  After this section: *Continue to next section* (Rating).",
        "",
        "## Section “Rating” (both tracks)",
        "",
        f"- **Q5 {fs.Q5}** — Multiple-choice grid, require a response in each row: on.",
        "  Columns: " + ", ".join(q(c) for c in fs.RATE_SCALE) + ".",
        "  Rows:",
        "",
    ]
    lines += [f"  {i}. `{s}`" for i, s in enumerate(fs.RATE_ITEMS, 1)]
    lines += [
        "",
        f"- **Q6 {fs.Q6}** — Paragraph, optional.",
        "",
        "## How Q4 maps to the taxonomy (M1)",
        "",
        "M1 counts a ticked option as a hit when one of its topics is among the company's top-10 most important "
        "topics by I(t).",
        "",
        "| Q4 option | Taxonomy v1.0 topics |",
        "|---|---|",
    ]
    lines += [f"| {o} | {', '.join(f'`{t}`' for t in ids)} |" for o, ids in fs.OPTION_TOPICS.items()]
    lines += [f"| {o} | unmapped — reported separately |" for o in fs.UNMAPPED]
    lines += [f"| {fs.CANNOT_RECALL} | excluded |", ""]
    return "\n".join(lines)


def main() -> None:
    for path in (fs.FORM_PATH, fs.TEMPLATE_PATH):
        os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(fs.FORM_PATH, "w", encoding="utf-8") as f:
        f.write(form_markdown())
    with open(fs.TEMPLATE_PATH, "w", encoding="utf-8", newline="") as f:
        csv.writer(f).writerow(fs.columns())
    print(f"Wrote {fs.FORM_PATH} and {fs.TEMPLATE_PATH}")


if __name__ == "__main__":
    main()
