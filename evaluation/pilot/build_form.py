"""
Writes, from evaluation/pilot/form_spec.py:
  docs/pilot/FORM.md            the form, question by question (two student tracks), and how to create it
  docs/pilot/create_form.gs     a Google Apps Script that builds the whole form
  data/pilot/pilot_template.csv the header of the form's CSV export

Usage:
    python evaluation/pilot/build_form.py
"""
import csv
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, ROOT)

from evaluation.pilot import form_spec as fs

FORM_TITLE = "PREPLINE pilot"
INFO_SHEET = ("PREPLINE compares the VIT CSE syllabus with topics companies ask in interviews. This form takes about "
              "10 minutes. Taking part is voluntary; you can skip questions and withdraw by giving the researcher your "
              "participant id before the analysis date. No name, email or roll number is collected. Answers are "
              "reported only as group averages.")
GRID_HELP = "How well does each gap match your real weak areas for this interview? 1 = not at all, 5 = exactly; N/A = can't judge."
USEFULNESS_HELP = "1 = strongly disagree, 5 = strongly agree."


def form_markdown() -> str:
    p, scored = fs.profiles(), fs.scored_profiles()
    q = lambda s: f"“{s}”"
    lines = [
        "# PREPLINE pilot — Google Form (students only, two tracks)",
        "",
        "Generated by `evaluation/pilot/build_form.py`; do not edit by hand. Titles must match",
        "`data/pilot/pilot_template.csv` exactly for the analysis to read the export.",
        "",
        "## Create the form with the script (recommended)",
        "",
        "1. Open https://script.google.com while signed in to the Google account that should own the form, and click",
        "   **New project**.",
        "2. Delete the sample code, paste the whole of `docs/pilot/create_form.gs`, and save (name it e.g. *PREPLINE pilot*).",
        "3. Select the function **createPrepLinePilotForm** in the toolbar and click **Run**; approve the permission",
        "   prompt (it only creates a form in your Drive).",
        "4. Open **Executions** (or View → Logs): the log prints the edit URL and the respondent URL of the new form.",
        "5. In the form, check Settings → Responses: **Collect email addresses = Do not collect** (the script sets it),",
        "   then send the respondent URL to participants with their participant ids.",
        "",
        "**Form settings if building by hand:** Do not collect email addresses. Do not require sign-in. No name field.",
        "",
        "## Section 1 — Consent, id and track (everyone)",
        "",
        f"Form description: {q(INFO_SHEET)}",
        "",
        f"1. **{fs.CONSENT}** — Checkboxes, required, one option: {q(fs.CONSENT_YES)}.",
        f"2. **{fs.PARTICIPANT}** — Short answer, required, regular expression `P[0-9]{{2}}`.",
        f"3. **{fs.TRACK}** — Multiple choice, required, go to section based on answer:",
        f"   - {q(fs.TRACK_A)} → Track A",
        f"   - {q(fs.TRACK_B)} → Track B",
        "",
        "## Track A — took an online assessment or interview",
        "",
        f"4. **{fs.COMPANY}** — Multiple choice, required, go to section based on answer: "
        + "; ".join(f"{q(x['label'])} → " + (f"{fs.GAP_PREFIX} {x['label']}" if x["gaps"] else "Usefulness") for x in p) + ".",
        f"5. **{fs.ROLE}** — Short answer, required.",
        f"6. **{fs.ROUNDS}** — Checkboxes: " + "; ".join(q(r) for r in fs.ROUND_OPTIONS) + ".",
        f"7. **{fs.TOPICS}** — Checkboxes (every topic asked in any round), plus {q(fs.NONE_OF_THESE)}:",
        "",
    ]
    lines += [f"   - {t}" for t in fs.topic_options()] + [f"   - {fs.NONE_OF_THESE}", ""]
    for x in scored:
        lines += [f"### {fs.GAP_PREFIX} {x['label']} (then go to Usefulness)", "",
                  f"Multiple-choice grid **{fs.GAP_PREFIX} {x['label']}**, columns " + ", ".join(fs.RATING_SCALE)
                  + f"; help text {q(GRID_HELP)}. Rows (copy exactly):", ""]
        lines += [f"- `{fs.gap_row(i, g)}`" for i, g in enumerate(x["gaps"], 1)] + [""]
    for x in p:
        if not x["gaps"]:
            lines += [f"*{x['label']} has no PREPLINE profile ({x['status']}): its Track A respondents go straight to "
                      "Usefulness.*", ""]
    lines += [
        "## Track B — any CSE student, after about 5 minutes on the dashboard",
        "",
        f"8. **{fs.COMPANY_B}** — Multiple choice, required: " + "; ".join(q(x["label"]) for x in scored) + ".",
        f"9. **{fs.PERCEIVED}** — Linear scale 1–5 (1 = not at all, 5 = exactly), required.",
        "",
        "## Usefulness (both tracks)",
        "",
        f"10. **{fs.USEFULNESS}** — Multiple-choice grid, columns 1–5 ({USEFULNESS_HELP}), rows:",
        "",
    ]
    lines += [f"- `{item}`" for item in fs.USEFULNESS_ITEMS]
    lines += ["", f"11. **{fs.COMMENTS}** — Paragraph, optional.", ""]
    return "\n".join(lines)


def apps_script() -> str:
    """Google Apps Script (FormApp) that builds the same form: section order Start, Track A, gap pages, Track B, Usefulness."""
    j = json.dumps
    p, scored = fs.profiles(), fs.scored_profiles()
    out = [
        "// Generated by evaluation/pilot/build_form.py from evaluation/pilot/form_spec.py. Do not edit by hand.",
        "// Run createPrepLinePilotForm() once at script.google.com; see docs/pilot/FORM.md.",
        "function createPrepLinePilotForm() {",
        f"  var form = FormApp.create({j(FORM_TITLE)});",
        f"  form.setDescription({j(INFO_SHEET)});",
        "  // Never collect email addresses (newer API first, older API as fallback).",
        "  try { form.setEmailCollectionType(FormApp.EmailCollectionType.DO_NOT_COLLECT); } catch (e) { form.setCollectEmail(false); }",
        "  form.setAllowResponseEdits(false);",
        "  form.setShowLinkToRespondAgain(false);",
        "",
        "  // Section 1: consent, participant id, track",
        f"  var consent = form.addCheckboxItem().setTitle({j(fs.CONSENT)}).setRequired(true);",
        f"  consent.setChoices([consent.createChoice({j(fs.CONSENT_YES)})]);",
        f"  form.addTextItem().setTitle({j(fs.PARTICIPANT)}).setRequired(true)",
        "    .setValidation(FormApp.createTextValidation().requireTextMatchesPattern('P[0-9]{2}').build());",
        f"  var track = form.addMultipleChoiceItem().setTitle({j(fs.TRACK)}).setRequired(true);",
        "",
        "  // Track A",
        "  var pageA = form.addPageBreakItem().setTitle('Track A: your assessment or interview');",
        f"  var company = form.addMultipleChoiceItem().setTitle({j(fs.COMPANY)}).setRequired(true);",
        f"  form.addTextItem().setTitle({j(fs.ROLE)}).setRequired(true);",
        f"  form.addCheckboxItem().setTitle({j(fs.ROUNDS)}).setChoiceValues({j(fs.ROUND_OPTIONS)});",
        f"  form.addCheckboxItem().setTitle({j(fs.TOPICS)}).setChoiceValues({j(fs.topic_options() + [fs.NONE_OF_THESE])});",
        "",
        "  // One gap-rating page per company with a PREPLINE profile",
        "  var gapPages = {};",
    ]
    for x in scored:
        rows = [fs.gap_row(i, g) for i, g in enumerate(x["gaps"], 1)]
        out += [
            f"  gapPages[{j(x['label'])}] = form.addPageBreakItem().setTitle({j(fs.GAP_PREFIX + ' ' + x['label'])});",
            f"  form.addGridItem().setTitle({j(fs.GAP_PREFIX + ' ' + x['label'])}).setHelpText({j(GRID_HELP)})",
            f"    .setRows({j(rows)}).setColumns({j(fs.RATING_SCALE)});",
        ]
    out += [
        "",
        "  // Track B",
        "  var pageB = form.addPageBreakItem().setTitle('Track B: after about 5 minutes on the PREPLINE dashboard');",
        f"  form.addMultipleChoiceItem().setTitle({j(fs.COMPANY_B)}).setRequired(true).setChoiceValues({j([x['label'] for x in scored])});",
        f"  form.addScaleItem().setTitle({j(fs.PERCEIVED)}).setBounds(1, 5).setLabels('Not at all', 'Exactly').setRequired(true);",
        "",
        "  // Usefulness (both tracks)",
        "  var pageUse = form.addPageBreakItem().setTitle('Usefulness');",
        f"  form.addGridItem().setTitle({j(fs.USEFULNESS)}).setHelpText({j(USEFULNESS_HELP)})",
        f"    .setRows({j(fs.USEFULNESS_ITEMS)}).setColumns(['1', '2', '3', '4', '5']);",
        f"  form.addParagraphTextItem().setTitle({j(fs.COMMENTS)});",
        "",
        "  // Navigation: track -> A or B; company -> its gap page (or Usefulness); every gap page and Track B end at Usefulness.",
        f"  track.setChoices([track.createChoice({j(fs.TRACK_A)}, pageA), track.createChoice({j(fs.TRACK_B)}, pageB)]);",
        "  company.setChoices([",
    ]
    out += [f"    company.createChoice({j(x['label'])}, " + (f"gapPages[{j(x['label'])}]" if x["gaps"] else "pageUse") + "),"
            for x in p]
    out += [
        "  ]);",
        "  // A page break's goToPage decides where the section before it continues.",
        "  var breaks = form.getItems(FormApp.ItemType.PAGE_BREAK).map(function (i) { return i.asPageBreakItem(); });",
        "  var gapIds = Object.keys(gapPages).map(function (k) { return gapPages[k].getId(); });",
        "  for (var b = 1; b < breaks.length; b++) {",
        "    if (gapIds.indexOf(breaks[b - 1].getId()) >= 0) breaks[b].setGoToPage(pageUse);",
        "  }",
        "  Logger.log('Edit URL: ' + form.getEditUrl());",
        "  Logger.log('Respondent URL: ' + form.getPublishedUrl());",
        "}",
        "",
    ]
    return "\n".join(out)


def main() -> None:
    for path in (fs.FORM_PATH, fs.SCRIPT_PATH, fs.TEMPLATE_PATH):
        os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(fs.FORM_PATH, "w", encoding="utf-8") as f:
        f.write(form_markdown())
    with open(fs.SCRIPT_PATH, "w", encoding="utf-8") as f:
        f.write(apps_script())
    with open(fs.TEMPLATE_PATH, "w", encoding="utf-8", newline="") as f:
        csv.writer(f).writerow(fs.columns())
    print(f"Wrote {fs.FORM_PATH}, {fs.SCRIPT_PATH} and {fs.TEMPLATE_PATH}")


if __name__ == "__main__":
    main()
