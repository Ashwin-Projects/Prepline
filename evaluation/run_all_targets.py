"""
Runs the full pipeline for every company/role target in config/targets.json against one syllabus, writes one
versioned results file per target, and regenerates results/COMPARISON.md from those files.

Results files are never overwritten (Deprecation & Migration): a target whose results file already exists is not
re-run, and its existing file is used for the comparison. To re-run a target, choose another --out-dir (or remove the
file deliberately). The syllabus is parsed at most once and shared, and only when some target passes the density gate.

Usage:
    python evaluation/run_all_targets.py
    python evaluation/run_all_targets.py --pdf-dir data/raw/syllabi --glob "B[CM]*.pdf" --out-dir results
"""
import argparse
import csv
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

import evaluation.run_full_pipeline as rfp
from pipeline.config import load_targets
from pipeline.syllabus_parser import parse_syllabus_pdfs

DEFAULT_PDF_DIR = os.path.join(ROOT, "data", "raw", "syllabi")
DEFAULT_GLOB = "B[CM]*.pdf"
DEFAULT_SYLLABUS_ID = "VIT_CSE_2024_25_courses"
DEFAULT_SUFFIX = "course_syllabi"
DEFAULT_OUT_DIR = os.path.join(ROOT, "results")


def results_path(out_dir: str, target_id: str, suffix: str = DEFAULT_SUFFIX) -> str:
    return os.path.join(out_dir, f"{target_id}_{rfp.RESULTS_VERSION}_{suffix}.json")


def count_raw_reports(reports_csv: str) -> int:
    """Rows of the target's reports.csv with a report_id: every collected report, before interview filtering."""
    with open(reports_csv, encoding="utf-8") as f:
        return sum(1 for row in csv.DictReader(f) if (row.get("report_id") or "").strip())


def _display_path(path: str) -> str:
    rel = os.path.relpath(path, ROOT) if os.path.splitdrive(path)[0] == os.path.splitdrive(ROOT)[0] else path
    return (path if rel.startswith("..") else rel).replace(os.sep, "/")


def run_all(targets: list, out_dir: str, pdf_paths: list = (), syllabus_id: str = DEFAULT_SYLLABUS_ID,
            transcriptions_dir: str = None, parse=None, comparison_out: str = None) -> list:
    """
    One results file per target in out_dir, then the comparison (default <out_dir>/COMPARISON.md).
    parse: zero-argument function returning the parsed syllabus (default: parse pdf_paths as one combined syllabus).
    Returns one entry per target: target, result, results_file, raw_report_count, reused.
    """
    cache = []

    def shared_parse():
        if not cache:
            cache.append(parse() if parse else parse_syllabus_pdfs(
                list(pdf_paths), syllabus_id=syllabus_id, transcriptions_dir=transcriptions_dir))
        return cache[0]

    os.makedirs(out_dir, exist_ok=True)
    entries = []
    for target in targets:
        out = results_path(out_dir, target["id"])
        reused = os.path.exists(out)
        if reused:
            print(f"[{target['id']}] results file exists, not re-run: {out}", flush=True)
            with open(out, encoding="utf-8") as f:
                result = json.load(f)
        else:
            print(f"[{target['id']}] running {target['company']} {target['role']}...", flush=True)
            result = rfp.run(list(pdf_paths), target, syllabus_id=syllabus_id, transcriptions_dir=transcriptions_dir,
                             parse=shared_parse)
            with open(out, "w", encoding="utf-8") as f:
                json.dump(result, f, indent=2)
            print(f"[{target['id']}] {result['status']}, S_comp {result['S_comp']}; saved to {out}", flush=True)
        entries.append({"target": target, "result": result, "results_file": _display_path(out),
                        "raw_report_count": count_raw_reports(target["reports_csv"]), "reused": reused})

    comparison_out = comparison_out or os.path.join(out_dir, "COMPARISON.md")
    with open(comparison_out, "w", encoding="utf-8") as f:
        f.write(build_comparison(entries))
    print(f"Comparison written to {comparison_out}", flush=True)
    return entries


def _gate(report_count: int) -> str:
    if report_count >= rfp.MIN_REPORTS:
        return f"PASSED ({report_count} ≥ {rfp.MIN_REPORTS})"
    return f"FAILED ({report_count} < {rfp.MIN_REPORTS})"


def _s_comp(result: dict) -> str:
    return "n/a" if result.get("S_comp") is None else str(result["S_comp"])


def build_comparison(entries: list) -> str:
    lines = [
        f"# Target comparison (results {rfp.RESULTS_VERSION})",
        "",
        "Generated by `evaluation/run_all_targets.py` from the results files named below. Do not edit by hand: "
        "re-run the script after adding a target or a results file.",
        "",
        "Report counts: *raw* = reports in the target's `reports.csv`; *after filtering* = reports with at least one "
        "question left after the interview filter (behavioral rounds, `needs_review` rows and rows without question "
        f"text are removed). The density gate needs at least {rfp.MIN_REPORTS} filtered reports.",
        "",
        "| Target | Reports (raw) | Reports (after filtering) | Density gate | Status | S_comp |",
        "|---|---|---|---|---|---|",
    ]
    for e in entries:
        t, r = e["target"], e["result"]
        lines.append(f"| {t['company']} {t['role']} | {e['raw_report_count']} | {r['report_count']} | "
                     f"{_gate(r['report_count'])} | {r['status']} | {_s_comp(r)} |")
    for e in entries:
        lines += [""] + _target_section(e)
    return "\n".join(lines) + "\n"


def _target_section(e: dict) -> list:
    t, r = e["target"], e["result"]
    origin = "kept from an earlier run" if e["reused"] else "written by this run"
    lines = [
        f"## {t['company']} {t['role']} (`{t['id']}`)",
        "",
        f"Results file: `{e['results_file']}` ({origin}). Syllabus: `{r.get('syllabus_id')}`, "
        f"scoring config {r.get('scoring_config_version')}, taxonomy {r.get('taxonomy_version')}.",
        "",
        "| Indicator | Value |",
        "|---|---|",
        f"| Reports (raw / after filtering) | {e['raw_report_count']} / {r['report_count']} |",
    ]
    f = r.get("interview_filter")
    if f:
        lines.append(f"| Questions (included / excluded) | {f['questions_included']} / {f['questions_excluded']} |")
    lines += [f"| Density gate | {_gate(r['report_count'])} |", f"| S_comp | {_s_comp(r)} |"]
    if r["status"] != "SUCCESS":
        return lines + ["", "The pipeline stopped at the density gate: no S_comp, priority gaps or "
                            "confidence indicators."]

    depth_all, depth_present = r["depth_counts"]["all_topics"], r["depth_counts"]["present_topics"]
    unmapped = r["unmapped_terms_summary"]
    by_source = ", ".join(f"{k} {v}" for k, v in sorted(unmapped["distinct_terms_by_source_type"].items()))
    gaps = r["top_priority_gaps"]
    lines += [
        f"| Scoring universe (topics with I(t) > 0) | {r['scoring_universe_size']} |",
        f"| Topics present in the syllabus | {r['topics_present']} of {r['topics_in_taxonomy']} |",
        f"| Topics on fallback depth | {depth_all.get('fallback', 0)} of {r['topics_in_taxonomy']} |",
        f"| Present topics on fallback depth | {depth_present.get('fallback', 0)} of {r['topics_present']} |",
        f"| Unmapped terms (distinct) | {unmapped['distinct_terms']} ({by_source}) |",
        "",
        f"Top {len(gaps)} priority gaps:",
        "",
        "| # | Topic | I(t) | Coverage | PriorityGap |",
        "|---|---|---|---|---|",
    ]
    lines += [f"| {g['rank']} | {g['topic_name']} (`{g['topic_id']}`) | {g['importance']} | {g['coverage']} | "
              f"{g['priority_gap']} |" for g in gaps]
    return lines


def main():
    parser = argparse.ArgumentParser(description="Run every configured target and regenerate results/COMPARISON.md.")
    parser.add_argument("--targets-config", help="targets config (default config/targets.json)")
    parser.add_argument("--pdf-dir", default=DEFAULT_PDF_DIR, help="folder of course syllabus PDFs")
    parser.add_argument("--glob", default=DEFAULT_GLOB, help=f"file pattern inside --pdf-dir (default {DEFAULT_GLOB})")
    parser.add_argument("--syllabus-id", default=DEFAULT_SYLLABUS_ID)
    parser.add_argument("--transcriptions-dir", help="default: <pdf-dir>/transcribed if it exists")
    parser.add_argument("--out-dir", default=DEFAULT_OUT_DIR)
    parser.add_argument("--comparison-out", help="default: <out-dir>/COMPARISON.md")
    args = parser.parse_args()

    pdf_paths = rfp.resolve_pdf_paths([], args.pdf_dir, args.glob)
    if not pdf_paths:
        sys.exit(f"No syllabus PDFs found in {args.pdf_dir} matching '{args.glob}'")
    entries = run_all(load_targets(args.targets_config), args.out_dir, pdf_paths, syllabus_id=args.syllabus_id,
                      transcriptions_dir=args.transcriptions_dir or rfp.default_transcriptions_dir(args.pdf_dir),
                      comparison_out=args.comparison_out)
    for e in entries:
        print(f"  {e['target']['id']:<20} {e['result']['status']:<18} S_comp {_s_comp(e['result'])}")


if __name__ == "__main__":
    main()
