"""
run_all_targets: one versioned results file per configured target (never overwriting an existing one), the
syllabus parsed at most once and shared, and results/COMPARISON.md regenerated from those files on every run.
"""
import json
import sys

import evaluation.run_all_targets as rat
from evaluation.test_targets import write_target
from pipeline.config import load_targets

FAKE_SYLLABUS = {
    "syllabus_id": "fake", "taxonomy_version": "v1.0", "units_count": 0, "courses": [], "course_groups": [],
    "course_filter": {"dropped": [], "allowlisted_missing": []}, "skipped_modules": [], "two_pass_mappings": [],
    "text_layer": {"pages_without_text": [], "page_count": 0, "scanned_courses": []},
}


def _two_targets(tmp_path):
    """acme: 14 reports (stops at the density gate); beta: 16 reports (scored)."""
    (tmp_path / "a").mkdir()
    (tmp_path / "b").mkdir()
    return (load_targets(write_target(tmp_path / "a", reports=14))
            + load_targets(write_target(tmp_path / "b", target_id="beta_sde1", company="Beta", reports=16)))


def _counting_parser():
    calls = []

    def parse():
        calls.append(1)
        return FAKE_SYLLABUS
    return parse, calls


def test_results_path_is_versioned_per_target(tmp_path):
    assert rat.results_path(str(tmp_path), "microsoft_sde1") == str(tmp_path / "microsoft_sde1_v1.2_course_syllabi.json")


def test_one_results_file_per_target_and_comparison(tmp_path):
    parse, calls = _counting_parser()
    out_dir = tmp_path / "results"
    entries = rat.run_all(_two_targets(tmp_path), str(out_dir), parse=parse)

    acme = json.loads((out_dir / "acme_sde1_v1.2_course_syllabi.json").read_text(encoding="utf-8"))
    beta = json.loads((out_dir / "beta_sde1_v1.2_course_syllabi.json").read_text(encoding="utf-8"))
    assert (acme["company"], acme["status"], acme["report_count"]) == ("Acme", "INSUFFICIENT_DATA", 14)
    assert (beta["company"], beta["status"], beta["report_count"]) == ("Beta", "SUCCESS", 16)
    assert beta["target_id"] == "beta_sde1"
    assert len(calls) == 1  # parsed once, only for the target past the density gate
    assert [e["raw_report_count"] for e in entries] == [14, 16]

    md = (out_dir / "COMPARISON.md").read_text(encoding="utf-8")
    assert "Generated by `evaluation/run_all_targets.py`" in md
    assert "## Acme SDE-1 (`acme_sde1`)" in md and "## Beta SDE-1 (`beta_sde1`)" in md
    assert "| Acme SDE-1 | 14 | 14 | FAILED (14 < 15) | INSUFFICIENT_DATA | n/a |" in md
    assert "| Beta SDE-1 | 16 | 16 | PASSED (16 ≥ 15) | SUCCESS | 0.0 |" in md
    assert beta["top_priority_gaps"][0]["topic_id"] in md.split("## Beta SDE-1", 1)[1]


def test_existing_results_file_is_kept_and_reused(tmp_path):
    out_dir = tmp_path / "results"
    out_dir.mkdir()
    existing = out_dir / "acme_sde1_v1.2_course_syllabi.json"
    existing.write_text(json.dumps({"company": "Acme", "role": "SDE-1", "status": "INSUFFICIENT_DATA",
                                    "report_count": 3, "S_comp": None}), encoding="utf-8")
    before = existing.read_text(encoding="utf-8")
    parse, calls = _counting_parser()
    targets = [t for t in _two_targets(tmp_path) if t["id"] == "acme_sde1"]

    entries = rat.run_all(targets, str(out_dir), parse=parse)

    assert existing.read_text(encoding="utf-8") == before
    assert entries[0]["reused"] is True and entries[0]["result"]["report_count"] == 3
    assert calls == []
    assert "| Acme SDE-1 | 14 | 3 |" in (out_dir / "COMPARISON.md").read_text(encoding="utf-8")


def _success(fallback=3, unmapped=1305, interview_terms=50):
    return {
        "company": "Microsoft", "role": "SDE-1", "status": "SUCCESS", "report_count": 15, "S_comp": 72.5,
        "scoring_universe_size": 12, "topics_present": 80, "topics_in_taxonomy": 83,
        "depth_counts": {"all_topics": {"measured": 83 - fallback, "fallback": fallback},
                         "present_topics": {"measured": 80}},
        "unmapped_terms_summary": {"distinct_terms": unmapped,
                                   "distinct_terms_by_source_type": {"syllabus": 1258, "interview": interview_terms},
                                   "total_occurrences": 1631},
        "interview_filter": {"questions_included": 71, "questions_excluded": 81},
        "top_priority_gaps": [{"rank": 1, "topic_id": "dsa.heaps.top_k", "topic_name": "Top K", "importance": 0.2,
                               "coverage": 0.5, "priority_gap": 0.1}],
    }


def test_comparison_confidence_indicators():
    target = {"id": "microsoft_sde1", "company": "Microsoft", "role": "SDE-1"}
    md = rat.build_comparison([{"target": target, "result": _success(), "raw_report_count": 17,
                                "results_file": "results/microsoft_sde1_v1.2_course_syllabi.json", "reused": False}])
    section = md.split("## Microsoft SDE-1 (`microsoft_sde1`)", 1)[1]
    assert "| Reports (raw / after filtering) | 17 / 15 |" in section
    assert "| Density gate | PASSED (15 ≥ 15) |" in section
    assert "| Topics on fallback depth | 3 of 83 |" in section
    assert "| Unmapped terms (distinct) | 1305 (interview 50, syllabus 1258) |" in section
    assert "| 1 | Top K (`dsa.heaps.top_k`) | 0.2 | 0.5 | 0.1 |" in section


def test_cli_regenerates_comparison(tmp_path, monkeypatch):
    config = write_target(tmp_path, reports=14)
    (tmp_path / "syllabi").mkdir()
    (tmp_path / "syllabi" / "BCSE202L.pdf").write_bytes(b"%PDF-1.4")
    out_dir = tmp_path / "results"
    monkeypatch.setattr(sys, "argv", ["run_all_targets.py", "--targets-config", config, "--out-dir", str(out_dir),
                                      "--pdf-dir", str(tmp_path / "syllabi")])
    rat.main()
    assert (out_dir / "acme_sde1_v1.2_course_syllabi.json").exists()
    assert "## Acme SDE-1 (`acme_sde1`)" in (out_dir / "COMPARISON.md").read_text(encoding="utf-8")
